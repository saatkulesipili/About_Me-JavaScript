// Basic Math Operations

let number1 = 5;
let number2 = 47;
let number3 = 13;
let number4 = 34.444444;

// Console Output

// addition
let addition = number1 + number2 + number3;
let addition2 = number1 + number4;
console.log("addition:" , addition);


console.log(addition2); // 39.444444
console.log(addition2.toFixed(2)); // 39.44

// Subtraction
let subtraction = number2 - number4;
console.log(subtraction);  //12.555556000000003
console.log(subtraction.toFixed(8));  // 12.55555600


// Multiplication
let multiplication = number2 * number3;
console.log(multiplication);

// Division
let division = number1 / number2;
console.log(division);  // 0.10638297872340426
console.log(division.toFixed(0)); // 0

